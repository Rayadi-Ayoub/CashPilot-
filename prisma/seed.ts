import { ExpenseStatus, InvoiceStatus, PrismaClient, Role } from "@prisma/client";
import bcrypt from "bcryptjs";
import PDFDocument from "pdfkit";
import { mkdir, rm, writeFile } from "fs/promises";
import path from "path";

const db = new PrismaClient();
const companyId = "cashpilot-demo-company";
const ownerId = "cashpilot-demo-owner";
const managerId = "cashpilot-demo-manager";
const collaboratorId = "cashpilot-demo-collaborator";

function day(offset: number) {
  const date = new Date();
  date.setHours(0, 0, 0, 0);
  date.setDate(date.getDate() + offset);
  return date;
}

async function createReceipt(company: string) {
  const directory = path.join(process.cwd(), "data", "uploads", company);
  await rm(directory, { recursive: true, force: true });
  await mkdir(directory, { recursive: true });
  const document = new PDFDocument({ size: "A4", margin: 60 });
  const chunks: Buffer[] = [];
  document.on("data", (chunk: Buffer) => chunks.push(chunk));
  const completed = new Promise<Buffer>((resolve) => document.on("end", () => resolve(Buffer.concat(chunks))));
  document.fillColor("#126b4f").fontSize(24).text("CashPilot demo receipt");
  document.moveDown(2).fillColor("#17231f").fontSize(12).text("Atlas Office Supplies");
  document.text("Demo receipt for the CashPilot presentation.");
  document.moveDown().fontSize(18).text("Total: 250.00 DT");
  document.moveDown(2).fontSize(10).text("This file is generated by npm run db:seed. It is not a real purchase document.");
  document.end();
  await writeFile(path.join(directory, "demo-receipt.pdf"), await completed);
}

async function main() {
  await db.company.deleteMany({ where: { id: companyId } });
  await db.user.deleteMany({ where: { id: { in: [ownerId, managerId, collaboratorId] } } });
  const passwordHash = await bcrypt.hash("demo1234", 12);
  const year = new Date().getFullYear();

  await db.company.create({
    data: {
      id: companyId,
      name: "CashPilot Demo SARL",
      initialBalance: "5000.00",
      initialBalanceSetAt: day(0),
      memberships: {
        create: [
          { role: Role.OWNER, user: { create: { id: ownerId, name: "Amira Owner", email: "owner@cashpilot.demo", passwordHash } } },
          { role: Role.MANAGER, user: { create: { id: managerId, name: "Mehdi Manager", email: "manager@cashpilot.demo", passwordHash } } },
          { role: Role.COLLABORATOR, user: { create: { id: collaboratorId, name: "Sara Collaborator", email: "collaborator@cashpilot.demo", passwordHash } } },
        ],
      },
      contacts: {
        create: [
          { id: "cashpilot-demo-client", type: "CLIENT", name: "Carthage Retail", email: "accounts@carthage.example", phone: "+216 20 100 200", address: "Tunis" },
          { id: "cashpilot-demo-supplier", type: "SUPPLIER", name: "Atlas Office Supplies", email: "sales@atlas.example", phone: "+216 70 300 400", address: "Ariana" },
        ],
      },
    },
  });

  await db.invoice.create({
    data: {
      id: "cashpilot-demo-invoice",
      companyId,
      contactId: "cashpilot-demo-client",
      number: `INV-${year}-0001`,
      status: InvoiceStatus.VALIDATED,
      total: "3000.00",
      issueDate: day(0),
      dueDate: day(30),
      validatedAt: day(0),
      notes: "Main presentation invoice: 1,000 DT received, 2,000 DT remaining.",
      payments: { create: { id: "cashpilot-demo-payment", companyId, recordedById: managerId, amount: "1000.00", paidAt: day(0), method: "Bank transfer", reference: "DEMO-PARTIAL-1000" } },
    },
  });
  await db.invoice.create({
    data: { id: "cashpilot-demo-overdue", companyId, contactId: "cashpilot-demo-client", number: `INV-${year}-0002`, status: InvoiceStatus.VALIDATED, total: "500.00", issueDate: day(-35), dueDate: day(-5), validatedAt: day(-35), notes: "Overdue invoice for the dashboard alert." },
  });

  const receipt = { receiptName: "demo-receipt.pdf", receiptStoredName: "demo-receipt.pdf", receiptType: "application/pdf" };
  await db.expense.create({ data: { id: "cashpilot-demo-paid", companyId, submittedById: collaboratorId, reviewedById: ownerId, paidById: managerId, category: "Office supplies", description: "Printer and paper", amount: "250.00", expenseDate: day(0), status: ExpenseStatus.PAID, reviewedAt: day(0), reviewNote: "Approved for the office.", paidAt: day(0), ...receipt } });
  await db.expense.create({ data: { id: "cashpilot-demo-approved", companyId, submittedById: managerId, reviewedById: ownerId, category: "Services", description: "Planned maintenance contract", amount: "6500.00", expenseDate: day(10), status: ExpenseStatus.APPROVED, reviewedAt: day(0), reviewNote: "Approved; payment is scheduled.", ...receipt } });
  await db.expense.create({ data: { id: "cashpilot-demo-pending", companyId, submittedById: collaboratorId, category: "Travel", description: "Client visit transport", amount: "400.00", expenseDate: day(15), status: ExpenseStatus.PENDING, ...receipt } });
  await db.expense.create({ data: { id: "cashpilot-demo-rejected", companyId, submittedById: collaboratorId, reviewedById: ownerId, category: "Other", description: "Unbudgeted purchase", amount: "90.00", expenseDate: day(-2), status: ExpenseStatus.REJECTED, reviewedAt: day(-1), reviewNote: "Outside the current budget.", ...receipt } });
  await db.simulation.create({ data: { id: "cashpilot-demo-simulation", companyId, createdById: managerId, name: "Main customer pays 20 days late", delayInvoiceId: "cashpilot-demo-invoice", delayDays: 20 } });
  await createReceipt(companyId);

  console.log("Demo data ready. Accounts (password: demo1234):");
  console.log("  owner@cashpilot.demo");
  console.log("  manager@cashpilot.demo");
  console.log("  collaborator@cashpilot.demo");
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
}).finally(() => db.$disconnect());
