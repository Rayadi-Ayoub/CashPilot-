import PDFDocument from "pdfkit";
import { NextResponse } from "next/server";
import { getCompanyContext, requireManager } from "@/lib/auth";
import { db } from "@/lib/db";
import { formatDate, formatMoney } from "@/lib/format";
import { invoiceStatusLabels } from "@/lib/invoices";

export async function GET(_request: Request, { params }: { params: Promise<{ id: string }> }) {
  const { company, role } = await getCompanyContext();
  requireManager(role);
  const { id } = await params;
  const invoice = await db.invoice.findFirst({ where: { id, companyId: company.id }, include: { contact: true, company: true } });
  if (!invoice) return new NextResponse("Invoice not found", { status: 404 });

  const document = new PDFDocument({ size: "A4", margin: 55, info: { Title: invoice.number ?? "Draft invoice" } });
  const chunks: Buffer[] = [];
  document.on("data", (chunk: Buffer) => chunks.push(chunk));
  const completed = new Promise<Buffer>((resolve) => document.on("end", () => resolve(Buffer.concat(chunks))));

  document.fillColor("#126b4f").fontSize(26).text("CashPilot", { continued: false });
  document.fillColor("#17231f").fontSize(20).text(invoice.number ?? "DRAFT INVOICE", 55, 125);
  document.fontSize(10).fillColor("#64716b").text(`Status: ${invoiceStatusLabels[invoice.status]}`);
  document.moveDown(2);
  document.fontSize(11).fillColor("#17231f").text("From", { underline: true }).moveDown(0.4).text(invoice.company.name);
  document.moveDown().text("Bill to", { underline: true }).moveDown(0.4).text(invoice.contact.name);
  if (invoice.contact.email) document.text(invoice.contact.email);
  if (invoice.contact.address) document.text(invoice.contact.address);
  document.moveDown(2).text(`Issue date: ${invoice.issueDate ? formatDate(invoice.issueDate) : "Not issued"}`);
  document.text(`Due date: ${formatDate(invoice.dueDate)}`);
  document.moveDown(2).roundedRect(55, document.y, 485, 75, 6).fill("#e5f3ec");
  document.fillColor("#17231f").fontSize(12).text("TOTAL DUE", 75, document.y - 58);
  document.fontSize(24).text(formatMoney(invoice.total), 75, document.y + 5);
  if (invoice.notes) document.fontSize(11).text(`Notes: ${invoice.notes}`, 55, 470);
  if (invoice.cancellationReason) document.fillColor("#b43636").fontSize(11).text(`Cancelled: ${invoice.cancellationReason}`, 55, 520);
  document.fillColor("#64716b").fontSize(9).text("Generated by CashPilot", 55, 760);
  document.end();
  const pdf = await completed;
  return new NextResponse(new Uint8Array(pdf), { headers: { "Content-Type": "application/pdf", "Content-Disposition": `inline; filename="${invoice.number ?? "draft-invoice"}.pdf"` } });
}
